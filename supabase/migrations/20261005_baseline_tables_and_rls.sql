-- Baseline for the tables the app reads/writes, written to be safe to run on a project
-- that already has them (everything is "if not exists"). Makes sure the columns the app
-- uses exist and that row-level security limits each user to their own rows.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text,
  points integer not null default 0,
  xp integer not null default 0,
  level text,
  streak integer not null default 0,
  longest_streak integer not null default 0,
  games_played integer not null default 0,
  walk_away_count integer not null default 0,
  partner_email text,
  partner_name text,
  blocked_apps text[] not null default '{}',
  created_at timestamptz not null default now()
);
alter table public.profiles add column if not exists name text;
alter table public.profiles add column if not exists level text;
alter table public.profiles add column if not exists walk_away_count integer not null default 0;
alter table public.profiles add column if not exists partner_email text;
alter table public.profiles add column if not exists partner_name text;
alter table public.profiles add column if not exists blocked_apps text[] not null default '{}';

create table if not exists public.blocklist (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  domain text not null,
  created_at timestamptz not null default now(),
  unique (user_id, domain)
);

create table if not exists public.game_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  game_id text,
  score integer,
  played_at date not null default current_date,
  created_at timestamptz not null default now()
);

create table if not exists public.journal_entries (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  text text not null,
  domain text,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.blocklist enable row level security;
alter table public.game_sessions enable row level security;
alter table public.journal_entries enable row level security;

do $$
begin
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='profiles' and policyname='own profile') then
    create policy "own profile" on public.profiles for all using (auth.uid() = id) with check (auth.uid() = id);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='blocklist' and policyname='own blocklist') then
    create policy "own blocklist" on public.blocklist for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='game_sessions' and policyname='own sessions') then
    create policy "own sessions" on public.game_sessions for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
  end if;
  if not exists (select 1 from pg_policies where schemaname='public' and tablename='journal_entries' and policyname='own journal') then
    create policy "own journal" on public.journal_entries for all using (auth.uid() = user_id) with check (auth.uid() = user_id);
  end if;
end $$;
